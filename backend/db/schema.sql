DROP TABLE IF EXISTS sessions, login_attempts, identity_links, order_items, orders, books, customers;

CREATE TABLE customers (
    -- Generated for customers created on first login; the seed sets its own ids.
    id    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name  text NOT NULL,
    email text NOT NULL UNIQUE
);

CREATE TABLE books (
    id        integer PRIMARY KEY,
    title     text NOT NULL,
    author    text NOT NULL,
    section   text NOT NULL CHECK (section IN ('classic-novels', 'adventure-sci-fi', 'philosophy', 'self-help')),
    is_signed boolean NOT NULL DEFAULT false,
    price     numeric(8, 2) NOT NULL,  -- current list price; changes over time
    stock     integer NOT NULL DEFAULT 0  -- not used until write actions (slice 2)
);

CREATE TABLE orders (
    id              integer PRIMARY KEY,
    customer_id     integer NOT NULL REFERENCES customers (id),
    status          text NOT NULL CHECK (status IN ('processing', 'shipped', 'delivered')),
    shipping_method text NOT NULL CHECK (shipping_method IN ('standard', 'express')),
    shipping_cost   numeric(8, 2) NOT NULL,
    promotion       text CHECK (promotion IN ('jules-verne-discount', 'self-help-discount', 'buy-5-get-the-cheapest-free')),
    created_at      timestamptz NOT NULL,
    shipped_at      timestamptz,
    delivered_at    timestamptz
);

-- Prices are snapshotted per line at purchase time, so refunds don't depend on today's books.price.
CREATE TABLE order_items (
    order_id   integer NOT NULL REFERENCES orders (id),
    book_id    integer NOT NULL REFERENCES books (id),
    unit_price numeric(8, 2) NOT NULL,
    discount   numeric(8, 2) NOT NULL DEFAULT 0,
    paid       numeric(8, 2) NOT NULL,
    PRIMARY KEY (order_id, book_id)
);

-- External identities (Keycloak today, Slack later) linked to a customer. Looked up by
-- (provider, external_id) only: the email is used once, to link, and never again.
CREATE TABLE identity_links (
    customer_id integer NOT NULL REFERENCES customers (id),
    provider    text NOT NULL CHECK (provider IN ('keycloak')),
    external_id text NOT NULL,
    linked_at   timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (provider, external_id)
);

-- A login in progress: `state` and the PKCE verifier live here (server side), keyed by state and
-- deleted on first use. The browser holds only the state, in a short-lived cookie.
CREATE TABLE login_attempts (
    state         text PRIMARY KEY,
    code_verifier text NOT NULL,
    expires_at    timestamptz NOT NULL
);

-- Web sessions. The browser cookie is `id` (random, opaque); the tokens never leave the backend.
-- Deleting a row ends that session immediately. Tokens are plain text: fine for a local lab,
-- encrypt them at rest before anything real.
CREATE TABLE sessions (
    id                text PRIMARY KEY,
    customer_id       integer NOT NULL REFERENCES customers (id),
    access_token      text NOT NULL,
    refresh_token     text NOT NULL,
    -- Kept only to tell Keycloak which session to end at logout (id_token_hint); never trusted.
    id_token          text NOT NULL,
    access_expires_at timestamptz NOT NULL,
    expires_at        timestamptz NOT NULL,
    created_at        timestamptz NOT NULL DEFAULT now()
);
